import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { tempStore, jpegWithExif } from './helpers.js';
const exec = promisify(execFile);
const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

test('本番用ラッパー：既存ストアで試し実行→登録→原本移動を行い、別途Node依存を要求しない', async () => {
  const { store, root, dataDir } = await tempStore();
  const kit = path.join(root, '名刺 kit');
  await fs.mkdir(path.join(kit, 'scripts'), { recursive: true });
  await fs.cp(path.join(project, 'dist/server'), path.join(kit, 'dist/server'), { recursive: true });
  await fs.copyFile(path.join(project, 'scripts/production-cli.mjs'), path.join(kit, 'scripts/production-cli.mjs'));
  await fs.writeFile(path.join(kit, 'package.json'), '{"type":"module"}');
  const inboxDir = path.join(root, 'inbox'); await fs.mkdir(inboxDir);
  const image = path.join(inboxDir, 'sample.jpg'); await fs.writeFile(image, jpegWithExif());
  const old = new Date(Date.now() - 60000); await fs.utimes(image, old, old);
  await fs.writeFile(path.join(kit, 'meishi-config.json'), JSON.stringify({ dataDir, inboxDir }));
  const form = path.join(kit, 'form.json');
  await fs.writeFile(form, JSON.stringify({ name: '架空試験', frontImageFile: image }));
  const run = (...args: string[]) => exec(process.execPath, [path.join(kit, 'scripts/production-cli.mjs'), ...args], { cwd: kit, env: { ...process.env, MEISHI_QUIET: '1' } });
  await run('check');
  const dry = JSON.parse((await run('dry-run', form)).stdout);
  assert.equal(dry.registered, 0);
  assert.equal(dry.failed, 0);
  assert.deepEqual(await fs.readdir(inboxDir), ['sample.jpg']);
  assert.deepEqual(await fs.readdir(path.join(dataDir, 'cards')), []);
  await fs.access(path.join(kit, 'preview/1-front.jpg'));
  const result = JSON.parse((await run('register', form)).stdout);
  assert.equal(result.registered, 1);
  assert.equal(result.results[0].movedFromInbox, 1);
  assert.deepEqual(result.results[0].inboxMoveFailed, []);
  assert.deepEqual(await fs.readdir(inboxDir), []);
  assert.equal((await fs.readdir(path.join(dataDir, 'inbox-done'))).length, 1);
  await store.refresh(true);
  assert.equal(store.list().length, 1);
  assert.equal(store.list()[0]!.backImage, null);
  const empty = path.join(root, 'not-initialized'); await fs.mkdir(empty);
  await fs.writeFile(path.join(kit, 'meishi-config.json'), JSON.stringify({ dataDir: empty, inboxDir }));
  await assert.rejects(run('check'));
  assert.deepEqual(await fs.readdir(empty), [], '保存先を勝手に初期化しない');
});
